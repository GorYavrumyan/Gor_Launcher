"""
Общий протокол IPC для фичи "выбрать обложку прямо во встроенном браузере".

Раньше (см. git-историю editors/game_editor.py) редактор игры открывал для
этого СВОЁ отдельное окно браузера (ImagePickerDialog) - неудобно, плюс
пользователь фактически работал в третьем окне вместо привычной вкладки
"Браузер" главного лаунчера.

Теперь редактор игры (отдельный процесс!) просит ГЛАВНЫЙ процесс лаунчера
самому переключиться на вкладку "Браузер", открыть там НОВУЮ вкладку в
специальном "режиме выбора обложки" и по завершении прислать обратно путь
к скачанному файлу. Именно поэтому нужен IPC между двумя процессами - без
него GameEditor физически не может дотянуться до чужого QTabWidget.

Транспорт: QLocalSocket/QLocalServer (Qt, работает и на Windows, и на
Linux/macOS без дополнительных библиотек). Формат сообщений: одна JSON-
строка на сообщение, разделитель - '\n'. Вынесено в отдельный модуль,
чтобы имя канала и формат сообщений не могли разъехаться между процессами
GorLauncher.py (сервер) и game_editor.py (клиент).
"""
import json

# Имя канала QLocalServer/QLocalSocket. Одно на всё приложение - лаунчер
# в любой момент времени запущен в единственном экземпляре.
IPC_SERVER_NAME = "GorLauncherCoverPickerIPC"

# Сколько мс клиент (редактор игры) ждёт подключения к серверу (главному
# лаунчеру), прежде чем решить, что тот не запущен, и откатиться на старый
# способ (отдельное окно ImagePickerDialog).
CONNECT_TIMEOUT_MS = 1500


def encode_message(data: dict) -> bytes:
    """Сериализует сообщение в байты для отправки через QLocalSocket."""
    return (json.dumps(data, ensure_ascii=False) + "\n").encode("utf-8")


def try_decode_line(buffer: bytes):
    """Пытается вытащить ОДНО полное сообщение из накопленного буфера
    байт. Возвращает (dict_или_None, остаток_буфера). Так как TCP/локальные
    сокеты не гарантируют, что придёт ровно одно сообщение за один сигнал
    readyRead, буфер нужно копить на стороне вызывающего кода и вызывать
    эту функцию, пока она не перестанет находить полные строки."""
    if b"\n" not in buffer:
        return None, buffer
    line, rest = buffer.split(b"\n", 1)
    line = line.strip()
    if not line:
        return None, rest
    try:
        return json.loads(line.decode("utf-8")), rest
    except (json.JSONDecodeError, UnicodeDecodeError):
        return None, rest
